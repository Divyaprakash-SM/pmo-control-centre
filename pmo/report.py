"""Builds the monthly steering-committee status pack as Markdown."""

from __future__ import annotations

import pandas as pd

from .metrics import (Portfolio, billing_reconciliation, gbp, portfolio_snapshot, project_commentary,
                      resource_exceptions, risk_register)

RAG_ICON = {"Green": "🟢", "Amber": "🟠", "Red": "🔴", "Grey": "⚪"}


def status_report(pf: Portfolio, as_of: str) -> str:
    snap = portfolio_snapshot(pf, as_of)
    recon = billing_reconciliation(pf, as_of)
    risks = risk_register(pf.risks, as_of)
    people = resource_exceptions(pf, as_of)
    month_label = pd.Period(as_of, "M").strftime("%B %Y")

    bac, eac = snap.budget_gbp.sum(), snap.eac.sum()
    leakage = recon[recon.finding != "Matched"].gap_gbp.clip(lower=0).sum()
    counts = snap.rag.value_counts()

    lines = [
        f"# Northwind Utilities Transformation Programme: Status Report, {month_label}",
        "",
        "*Synthetic data. Generated by PMO Control Centre.*",
        "",
        "## Headlines",
        f"- **Portfolio health:** {counts.get('Green', 0)} Green · {counts.get('Amber', 0)} Amber · "
        f"{counts.get('Red', 0)} Red across {len(snap)} projects.",
        f"- **Money:** budget {gbp(bac)}, forecast outturn {gbp(eac)} "
        f"({gbp(abs(eac - bac))} {'over' if eac > bac else 'under'} budget).",
        f"- **Revenue at risk:** {gbp(leakage)} of logged effort not yet invoiced.",
        f"- **Risk:** {int((risks.status != 'Closed').sum())} open risks, "
        f"{int(((risks.score >= 15) & (risks.status != 'Closed')).sum())} rated high, "
        f"{int(risks.overdue.sum())} actions overdue.",
        f"- **People:** {int((people.flag == 'Over-allocated').sum())} over-allocated, "
        f"{int((people.flag == 'Under-utilised').sum())} under-utilised.",
        "",
        "## Decisions requested",
    ]
    decisions = []
    for r in snap[snap.rag == "Red"].itertuples():
        decisions.append(f"- **{r.project_name}:** approve a re-baseline or recovery plan. "
                         f"Forecast overspend {gbp(-r.vac)}.")
    for (pid, finding), g in recon[recon.finding.str.startswith("Work")].groupby(["project_id", "finding"]):
        name, since = g.project_name.iloc[0], pd.Period(g.month.min(), "M").strftime("%B")
        action = "chase client signature" if "unsigned" in finding else "raise and sign an SOW extension"
        decisions.append(f"- **{name}:** {finding} since {since}. {gbp(g.gap_gbp.sum())} cannot be "
                         f"invoiced until the paperwork is fixed. Action: {action}.")
    lines += decisions or ["- None this period."]

    lines += ["", "## Project summary", "",
              "| Project | RAG | CPI | SPI | Budget | Forecast | Open risks |",
              "|---|---|---|---|---|---|---|"]
    for r in snap.sort_values("rag", key=lambda s: s.map({"Red": 0, "Amber": 1, "Green": 2})).itertuples():
        lines.append(f"| {r.project_name} | {RAG_ICON[r.rag]} {r.rag} | {r.cpi:.2f} | {r.spi:.2f} | "
                     f"{gbp(r.budget_gbp)} | {gbp(r.eac)} | {r.open_risks} |")

    lines += ["", "## Commentary on Red and Amber projects"]
    flagged = snap[snap.rag.isin(["Red", "Amber"])].sort_values("rag", key=lambda s: s.map({"Red": 0, "Amber": 1}))
    for _, r in flagged.iterrows():
        lines += ["", f"### {RAG_ICON[r.rag]} {r.project_name} ({r.project_manager})"]
        lines += [f"- {n}" for n in project_commentary(r, recon)]

    top = risks[risks.status != "Closed"].nlargest(5, "score").merge(pf.projects[["project_id", "project_name"]])
    lines += ["", "## Top 5 risks", "", "| Risk | Project | Score | Owner | Action due |", "|---|---|---|---|---|"]
    for r in top.itertuples():
        due = r.action_due_date.date().isoformat() + (" ⚠️ overdue" if r.overdue else "")
        lines.append(f"| {r.title} | {r.project_name} | {r.score} | {r.owner} | {due} |")
    return "\n".join(lines) + "\n"
